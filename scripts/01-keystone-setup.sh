#!/usr/bin/env bash
# Lab 02 - Keystone: project, users, roles, quotas, per-user credential files
set -eo pipefail
# shellcheck source=lib/common.sh
source "$(dirname "$0")/lib/common.sh"
load_openrc; as_admin

log "Project '$LAB_PROJECT'"
exists project show "$LAB_PROJECT" \
  || openstack project create --domain default --description "Private cloud lab" "$LAB_PROJECT"

for u in "$LAB_USER" "$LAB_READER"; do
  log "User '$u'"
  exists user show --domain default "$u" \
    || openstack user create --domain default --password "$LAB_PASSWORD" \
         --project "$LAB_PROJECT" "$u"
done

log "Role assignments (member -> $LAB_USER, reader -> $LAB_READER, admin -> admin)"
openstack role add --project "$LAB_PROJECT" --project-domain default \
  --user "$LAB_USER" --user-domain default member
openstack role add --project "$LAB_PROJECT" --project-domain default \
  --user "$LAB_READER" --user-domain default reader
openstack role add --project "$LAB_PROJECT" --project-domain default \
  --user admin --user-domain default admin

log "Quotas for '$LAB_PROJECT'"
openstack quota set --instances 6 --cores 8 --ram 6144 \
  --volumes 6 --gigabytes 20 --snapshots 6 "$LAB_PROJECT"

write_rc() { # write_rc <user> <file>
  local f="$LAB_ROOT/$2"
  cat > "$f" <<EOF
# Credentials for the lab - generated by 01-keystone-setup.sh (git-ignored)
export OS_AUTH_URL="$OS_AUTH_URL"
export OS_USERNAME="$1"
export OS_PASSWORD="$LAB_PASSWORD"
export OS_PROJECT_NAME="$LAB_PROJECT"
export OS_USER_DOMAIN_NAME="Default"
export OS_PROJECT_DOMAIN_NAME="Default"
export OS_IDENTITY_API_VERSION=3
export OS_REGION_NAME="${OS_REGION_NAME:-RegionOne}"
EOF
  chmod 600 "$f"
  echo "    wrote $f"
}
log "Credential files"
write_rc "$LAB_USER"   "labuser-openrc.sh"
write_rc "$LAB_READER" "labreader-openrc.sh"

log "Result"
openstack role assignment list --project "$LAB_PROJECT" --names
openstack quota show "$LAB_PROJECT" -c instances -c cores -c ram -c volumes -c gigabytes -c snapshots
